/**
 * Get FAQ for a given category, with fallback to 'general'
 */
export function getFaqForCategory(
  category: BlogCategorySlug | undefined
): CategoryFaq | null {
  if (!category) return CATEGORY_FAQ['general'] ?? null;
  return CATEGORY_FAQ[category] ?? CATEGORY_FAQ['general'] ?? null;
}
